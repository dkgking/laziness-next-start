// Pages are written once, under src/app/(site), where they are the default
// locale's (/todos). Every other locale has the same pages under its prefix
// (/vi/todos): Next.js needs a route file for each, so this script writes
// src/app/[locale] as a mirror of src/app/(site), each file handing over to
// the one it mirrors. With one locale there is no mirror at all.
//
// It runs whenever Next.js starts (next.config.ts) and follows new pages
// while the dev server runs. `bun run routes` runs it by hand.
import fs from "node:fs";
import path from "node:path";
import { defaultLocale, locales } from "../src/libs/locales.ts";

const APP_DIR = path.join(import.meta.dirname, "..", "src", "app");
const SOURCE_DIR = path.join(APP_DIR, "(site)");
const MIRROR_DIR = path.join(APP_DIR, "[locale]");

/** The files Next.js reads in a route's folder; anything else beside them is the page's own. */
const ROUTE_FILE =
	/^(page|layout|not-found|error|loading|template|default|forbidden|unauthorized)\.(tsx|ts|jsx|js)$/;

/** A route's settings, which Next.js reads from the route's own file. */
const SEGMENT_CONFIG =
	/^export const (dynamic|dynamicParams|revalidate|fetchCache|runtime|preferredRegion|maxDuration)\b.*;$/gm;

const CLIENT_DIRECTIVE = /^\s*["']use client["']/;

const HEADER =
	"// Generated by scripts/locale-routes.ts from src/app/(site): never edit.\n";

/** The route files under `dir`, as paths from it. */
const routeFiles = (dir: string, under = ""): string[] =>
	fs
		.readdirSync(path.join(dir, under), { withFileTypes: true })
		.flatMap((entry) => {
			const relative = path.posix.join(under, entry.name);
			if (entry.isDirectory()) return routeFiles(dir, relative);
			return ROUTE_FILE.test(entry.name) ? [relative] : [];
		});

const mirrorOf = (relative: string) => {
	const source = fs.readFileSync(path.join(SOURCE_DIR, relative), "utf8");
	const from = `#/app/(site)/${relative.replace(/\.[a-z]+$/, "")}`;
	// A Client Component's file may hand over only its default export.
	if (CLIENT_DIRECTIVE.test(source))
		return `"use client";\n\n${HEADER}export { default } from "${from}";\n`;
	const config = source.match(SEGMENT_CONFIG) ?? [];
	// The mirror's top layout is where its locales are named: only those are pages.
	const params =
		relative === "layout.tsx"
			? [
					"export const dynamicParams = false;",
					`export const generateStaticParams = () => ${JSON.stringify(
						locales
							.filter(({ code }) => code !== defaultLocale)
							.map(({ code }) => ({ locale: code })),
					)};`,
				]
			: [];
	return [
		`${HEADER}export * from "${from}";`,
		`export { default } from "${from}";`,
		...config,
		...params,
		"",
	].join("\n");
};

/** Makes src/app/[locale] mirror src/app/(site); removes it while the app has one locale. */
export function syncLocaleRoutes() {
	if (locales.length < 2) {
		fs.rmSync(MIRROR_DIR, { recursive: true, force: true });
		return;
	}
	const wanted = new Set(routeFiles(SOURCE_DIR));
	for (const relative of wanted) {
		const target = path.join(MIRROR_DIR, relative);
		const content = mirrorOf(relative);
		const current = fs.existsSync(target)
			? fs.readFileSync(target, "utf8")
			: null;
		if (current === content) continue;
		fs.mkdirSync(path.dirname(target), { recursive: true });
		fs.writeFileSync(target, content);
	}
	if (!fs.existsSync(MIRROR_DIR)) return;
	for (const relative of routeFiles(MIRROR_DIR))
		if (!wanted.has(relative)) fs.rmSync(path.join(MIRROR_DIR, relative));
	removeEmptyFolders(MIRROR_DIR);
}

function removeEmptyFolders(dir: string) {
	for (const entry of fs.readdirSync(dir, { withFileTypes: true }))
		if (entry.isDirectory()) removeEmptyFolders(path.join(dir, entry.name));
	if (dir !== MIRROR_DIR && fs.readdirSync(dir).length === 0) fs.rmdirSync(dir);
}

const WATCH_SETTLE_MS = 100;

/** Keeps the mirror in step while the dev server runs (a page added or removed under src/app/(site)). */
export function watchLocaleRoutes() {
	if (locales.length < 2) return;
	let timer: NodeJS.Timeout | undefined;
	fs.watch(SOURCE_DIR, { recursive: true }, () => {
		clearTimeout(timer);
		timer = setTimeout(() => {
			try {
				syncLocaleRoutes();
			} catch (error) {
				console.error("[locale-routes]", error);
			}
		}, WATCH_SETTLE_MS);
	});
}

if (import.meta.main) syncLocaleRoutes();
